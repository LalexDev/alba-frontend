BEGIN;

CREATE TABLE IF NOT EXISTS public.cuentas_manuales (
  id_cuenta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario UUID NOT NULL,
  cliente_nombre TEXT NOT NULL,
  cliente_telefono TEXT,
  referencia TEXT,
  fecha_venta DATE NOT NULL,
  montura TEXT NOT NULL,
  precio_venta NUMERIC(12,2) NOT NULL DEFAULT 0,
  total_venta NUMERIC(12,2) NOT NULL,
  monto_cancelado_historico NUMERIC(12,2) NOT NULL DEFAULT 0,
  estado TEXT NOT NULL DEFAULT 'PENDIENTE',
  observaciones TEXT,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT cuentas_manuales_precio_check
    CHECK (precio_venta >= 0),
  CONSTRAINT cuentas_manuales_total_check
    CHECK (total_venta > 0),
  CONSTRAINT cuentas_manuales_historico_check
    CHECK (
      monto_cancelado_historico >= 0 AND
      monto_cancelado_historico <= total_venta
    ),
  CONSTRAINT cuentas_manuales_estado_check
    CHECK (estado IN ('PENDIENTE', 'PAGADA'))
);

CREATE TABLE IF NOT EXISTS public.pagos_cuentas_manuales (
  id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cuenta BIGINT NOT NULL
    REFERENCES public.cuentas_manuales(id_cuenta)
    ON DELETE RESTRICT,
  id_caja BIGINT NOT NULL
    REFERENCES public.cajas(id_caja)
    ON DELETE RESTRICT,
  id_usuario UUID NOT NULL,
  monto NUMERIC(12,2) NOT NULL,
  metodo_pago TEXT NOT NULL,
  observaciones TEXT,
  fecha_pago TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pagos_cuentas_manuales_monto_check
    CHECK (monto > 0),
  CONSTRAINT pagos_cuentas_manuales_metodo_check
    CHECK (
      metodo_pago IN ('EFECTIVO', 'YAPE', 'TRANSFERENCIA')
    )
);

ALTER TABLE public.movimientos_caja
  ADD COLUMN IF NOT EXISTS id_cuenta_manual BIGINT;

DO $do$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'movimientos_caja_cuenta_manual_fkey'
      AND conrelid = 'public.movimientos_caja'::regclass
  ) THEN
    ALTER TABLE public.movimientos_caja
      ADD CONSTRAINT movimientos_caja_cuenta_manual_fkey
      FOREIGN KEY (id_cuenta_manual)
      REFERENCES public.cuentas_manuales(id_cuenta)
      ON DELETE RESTRICT;
  END IF;
END;
$do$;

